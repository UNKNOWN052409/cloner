// Store generator (C2 of the behavior-synthesis wave): compiles the behavior
// contract (behavior-model.json, C1) into the clone's generated BACKEND —
// runtime/store.js, an ES5 IIFE in the exact discipline of streams.js /
// app-state.js (embedded model, zero network, deterministic).
//
// What the generated store does:
//   1. STATE: one collection per behavior-model entity (fields = the captured
//      numeric keys), seeded deterministically (mulberry32 over a model hash —
//      same PRNG discipline as the hand-built reference store).
//   2. FEED CONTINUATION: streams.js replays the CAPTURED tape first; once it
//      reports done (window.__CLONER_STREAMS_DONE), the store keeps every feed
//      alive with a seeded random walk over its keys — publishing through the
//      SAME data-stream-target contract, so every wired widget updates. No
//      fight: the store never writes while the tape is playing.
//   3. ACTIONS: for each behavior-model action bound to a trigger that exists
//      in the clone (data-cloner-trigger), the store attaches a click listener
//      (event delegation) and dispatches. Submit-kind actions read the page's
//      captured form fields (name/type only — values are the USER's input),
//      mutate the mapped entity collection and emit a receipt.
//   4. LOG: every mutation appends a deterministic record to
//      window.__CLONER_STORE_LOG { t, action, kind, delta } — the assertion
//      surface for verify-behavior.js (C4) and the honesty contract for the
//      grade gate: what changed, when, by how much.
//
// Honest-scope: the store owns MUTATIONS and FEED LIFE. Navigation/open
// actions stay with the existing replay runtime (records, state pages) — a
// generated store must not duplicate what already replays faithfully.
//
// Integration (one call in reconstruction-pipeline.js, already wired):
//   augmentProjectWithStore(outDir, behavior, { artifactsDir, pages: genFiles })
import fs from "node:fs";
import path from "node:path";
import { stableStringify } from "../../exploration/websocket-session-capture.js";

export const STORE_RUNTIME_FILE = "runtime/store.js";

// store actions the generated runtime owns — everything else (navigate/open)
// is the replay runtime's lane
const OWNED_KINDS = new Set(["submit"]);

function hashSeed(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

// compact action records for the runtime: only what dispatch needs
function runtimeActions(model) {
  return (model.actions || [])
    .filter((a) => OWNED_KINDS.has(a.kind) && a.trigger)
    .map((a) => ({ id: a.trigger, actionId: a.id, kind: a.kind, label: a.label || "", fields: (a.evidence && a.evidence.fields) || [] }));
}

function runtimeFeeds(model) {
  return (model.feeds || [])
    .filter((f) => f.numeric && f.keys.length)
    .map((f) => ({ id: f.id, keys: f.keys, seed: (f.keys[0] || 1) }));
}

// buildStoreRuntime(model) → runtime/store.js source. Empty model → a
// documented no-op (still emitted so linking never 404s).
export function buildStoreRuntime(model) {
  const actions = runtimeActions(model || {});
  const feeds = runtimeFeeds(model || {});
  const entities = (model?.entities || []).map((e) => ({ id: e.id, kind: e.kind, keys: e.keys }));
  const payload = {
    schema: "1.0.0",
    seed: hashSeed(stableStringify({ a: actions, f: feeds, e: entities })),
    feeds,
    entities,
    actions,
  };
  return `// generated by generation/store-generator.js (C2 behavior synthesis) — embedded
// model, no network, deterministic. State: one collection per captured entity.
// Feeds: seeded random walk AFTER the captured stream tape completes (the
// replayer owns playback; the store owns continuation — they never fight).
// Actions: submit-kind triggers dispatch into the store and log a receipt.
// Log: window.__CLONER_STORE_LOG = [{ t, action, kind, delta }] (C4's surface).
(function () {
  var M = ${JSON.stringify(payload)};
  var LOG = [];
  var STATE = { entities: {}, meta: { startedAt: Date.now(), dispatched: 0 } };
  window.__CLONER_STORE_LOG = LOG;
  function log(entry) { if (LOG.length < 500) LOG.push(entry); }

  // ---- deterministic PRNG (mulberry32) — same discipline as the reference ----
  var s = M.seed >>> 0;
  function rnd() {
    s |= 0; s = (s + 0x6D2B79F5) | 0;
    var t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  // ---- state: one collection per entity, fields from the captured keys ----
  for (var ei = 0; ei < M.entities.length; ei++) {
    var ent = M.entities[ei];
    STATE.entities[ent.id] = { kind: ent.kind, fields: ent.keys, rows: [] };
  }

  // ---- feed continuation: seeded random walk over each feed's keys ----
  var channels = {};
  for (var fi = 0; fi < M.feeds.length; fi++) {
    var feed = M.feeds[fi];
    var vals = {};
    for (var ki = 0; ki < feed.keys.length; ki++) vals[feed.keys[ki]] = 100 + rnd() * 100;
    channels[feed.id] = { keys: vals };
  }
  function publish(channelId, data) {
    var els = document.querySelectorAll('[data-stream-target]');
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      var key = el.getAttribute('data-stream-target') || '';
      var parts = key.split('.');
      if (parts[0] !== channelId) continue;
      var field = parts[parts.length - 1];
      if (!(field in data)) continue;
      var v = data[field];
      el.textContent = String(v);
    }
    log({ t: Date.now() - STATE.meta.startedAt, action: 'feed:' + channelId, kind: 'feed', delta: data });
  }
  function stepFeeds() {
    for (var id in channels) {
      var ch = channels[id];
      var data = {};
      for (var k in ch.keys) {
        var drift = (rnd() - 0.5) * (Math.abs(ch.keys[k]) * 0.004 + 0.05);
        ch.keys[k] = Math.round((ch.keys[k] + drift) * 100) / 100;
        data[k] = ch.keys[k];
      }
      publish(id, data);
    }
  }
  function startFeeds() {
    if (M.feeds.length) setInterval(stepFeeds, 1000);
  }
  // the replayer owns the tape: wait for its done flag before continuation
  // starts; pages WITHOUT the streams runtime start immediately (there is no
  // tape to wait for — the grace timeout is only for a tape that never ends)
  var hasTape = !!document.querySelector('script[src*="streams.js"]');
  var tapeWait = 0;
  (function waitTape() {
    if (!hasTape || window.__CLONER_STREAMS_DONE || tapeWait > 30) startFeeds();
    else { tapeWait++; setTimeout(waitTape, 1000); }
  })();

  // ---- actions: submit-kind triggers dispatch into the store ----
  function readFormContext(el) {
    var out = {};
    try {
      var scope = el.closest('form') || el.parentElement || document;
      var fields = scope.querySelectorAll('input,select,textarea');
      for (var i = 0; i < fields.length && i < 12; i++) {
        var f = fields[i];
        var name = f.getAttribute('name') || f.id || ('field' + i);
        if ((f.getAttribute('type') || '').toLowerCase() === 'hidden') continue;
        out[name] = f.value !== '' && !isNaN(Number(f.value)) ? Number(f.value) : f.value;
      }
    } catch (e) {}
    return out;
  }
  function dispatch(actionId, triggerEl) {
    STATE.meta.dispatched++;
    var entry = { t: Date.now() - STATE.meta.startedAt, action: actionId, kind: 'submit', delta: null };
    try {
      var input = readFormContext(triggerEl);
      var target = null;
      for (var id in STATE.entities) if (STATE.entities[id].kind === 'collection') { target = id; break; }
      if (!target) { STATE.entities.orders = { kind: 'collection', fields: [], rows: [] }; target = 'orders'; }
      var row = Object.assign({ id: 'r' + STATE.meta.dispatched }, input);
      var rows = STATE.entities[target].rows;
      rows.push(row);
      if (rows.length > 50) rows.shift();
      entry.delta = { entity: target, rows: rows.length, input: input };
      log(entry);
      document.dispatchEvent(new CustomEvent('cloner-store', { detail: { action: actionId, entity: target } }));
    } catch (e) {
      entry.error = String(e && e.message || e).slice(0, 120);
      log(entry);
    }
    return entry;
  }
  document.addEventListener('click', function (ev) {
    var el = ev.target && ev.target.closest ? ev.target.closest('[data-cloner-trigger]') : null;
    if (!el) return;
    var id = el.getAttribute('data-cloner-trigger');
    for (var i = 0; i < M.actions.length; i++) {
      if (M.actions[i].id === id) { dispatch(M.actions[i].actionId, el); break; }
    }
  }, false);

  window.__CLONER_STORE = {
    state: STATE,
    channels: channels,
    dispatch: dispatch,
    log: LOG,
    model: { feeds: M.feeds.length, entities: M.entities.length, actions: M.actions.length },
  };
})();
`;
}

// augmentProjectWithStore(outDir, model, opts) — one-call hook: writes
// runtime/store.js and links it into the generated pages. Returns
// { applied, runtimeFile, linked, notes }.
export function augmentProjectWithStore(outDir, model, opts = {}) {
  const notes = [];
  const result = { applied: false, runtimeFile: STORE_RUNTIME_FILE, linked: 0, notes };
  const actions = runtimeActions(model || {});
  const feeds = runtimeFeeds(model || {});
  if (!actions.length && !feeds.length) {
    notes.push("behavior model carries no store-ownable actions/feeds — runtime not emitted (honest skip)");
    return result;
  }
  const pages = (opts.pages && opts.pages.length ? opts.pages : ["index.html"]).filter((p) => typeof p === "string");
  try { fs.mkdirSync(path.join(outDir, "runtime"), { recursive: true }); } catch (e) { notes.push("runtime dir: " + String(e?.message || e).slice(0, 60)); }
  fs.writeFileSync(path.join(outDir, STORE_RUNTIME_FILE), buildStoreRuntime(model));
  result.applied = true;
  const tag = '<script src="' + STORE_RUNTIME_FILE + '"></script>';
  const anchor = '<script src="runtime/app-state.js"></script>';
  for (const rel of pages) {
    const fp = path.join(outDir, rel);
    if (!fs.existsSync(fp)) continue;
    let html = fs.readFileSync(fp, "utf8");
    if (html.includes(tag)) { result.linked++; continue; } // idempotent
    if (html.includes(anchor)) {
      html = html.replace(anchor, anchor + "\n  " + tag);
    } else if (html.includes('<script src="runtime/interactions.js"></script>')) {
      html = html.replace('<script src="runtime/interactions.js"></script>', '<script src="runtime/interactions.js"></script>\n  ' + tag);
    } else if (html.includes("</body>")) {
      html = html.replace("</body>", "  " + tag + "\n</body>");
    } else { notes.push(rel + ": no script/body anchor — not linked"); continue; }
    fs.writeFileSync(fp, html);
    result.linked++;
  }
  if (!result.linked) notes.push("store runtime not linked into any page");
  return result;
}
